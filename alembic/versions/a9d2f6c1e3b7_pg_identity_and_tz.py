def _is_postgres() -> bool:
    bind = op.get_bind()
    return bind.dialect.name == "postgresql"


def _add_identity(table: str) -> None:
    """Idempotently add ``GENERATED BY DEFAULT AS IDENTITY`` to ``id``.

    Skips the ALTER if the column is already IDENTITY or already has a
    DEFAULT (e.g. a serial sequence from a different code path). The
    starting value is computed at migration time from ``MAX(id)+1`` so
    existing rows aren't disturbed; for an empty table the sequence
    starts at 1.
    """
    op.execute(
        f"""
        DO $$
        DECLARE
            has_identity text;
            has_default text;
            tbl_exists int;
            start_val bigint;
        BEGIN
            SELECT count(*) INTO tbl_exists
            FROM information_schema.tables
            WHERE table_schema = current_schema()
              AND table_name = '{table}';
            IF tbl_exists = 0 THEN
                RAISE NOTICE 'skip identity: table % missing', '{table}';
                RETURN;
            END IF;

            SELECT is_identity, column_default
              INTO has_identity, has_default
            FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = '{table}'
              AND column_name = 'id';

            IF has_identity IS NULL THEN
                RAISE NOTICE 'skip identity: column id missing on %', '{table}';
                RETURN;
            END IF;

            IF has_identity = 'YES' OR has_default IS NOT NULL THEN
                RAISE NOTICE 'skip identity: % already auto-incrementing', '{table}';
                RETURN;
            END IF;

            EXECUTE format(
                'SELECT COALESCE(MAX(id), 0) + 1 FROM %I',
                '{table}'
            ) INTO start_val;

            EXECUTE format(
                'ALTER TABLE %I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',
                '{table}', start_val
            );
        END
        $$;
        """
    )


def _drop_identity(table: str) -> None:
    """Idempotently drop IDENTITY from ``id``.

    Uses ``DROP IDENTITY IF EXISTS`` (Postgres 10+). Safe to run when
    the column is not an identity column or the table is missing.
    """
    op.execute(
        f"""
        DO $$
        DECLARE
            tbl_exists int;
        BEGIN
            SELECT count(*) INTO tbl_exists
            FROM information_schema.tables
            WHERE table_schema = current_schema()
              AND table_name = '{table}';
            IF tbl_exists = 0 THEN
                RETURN;
            END IF;
            EXECUTE format(
                'ALTER TABLE %I ALTER COLUMN id DROP IDENTITY IF EXISTS',
                '{table}'
            );
        END
        $$;
        """
    )


def _convert_to_timestamptz(table: str, column: str) -> None:
    """Idempotently convert a column to ``TIMESTAMP WITH TIME ZONE``.

    Skips if already ``timestamp with time zone`` or if the table /
    column is missing. The ``USING ... AT TIME ZONE 'UTC'`` clause
    treats any existing naive timestamps as UTC, matching what the
    application code has been writing.
    """
    op.execute(
        f"""
        DO $$
        DECLARE
            current_type text;
        BEGIN
            SELECT data_type INTO current_type
            FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = '{table}'
              AND column_name = '{column}';

            IF current_type IS NULL THEN
                RAISE NOTICE 'skip tz convert: % . % missing', '{table}', '{column}';
                RETURN;
            END IF;

            IF current_type = 'timestamp with time zone' THEN
                RAISE NOTICE 'skip tz convert: % . % already tz-aware', '{table}', '{column}';
                RETURN;
            END IF;

            EXECUTE format(
                'ALTER TABLE %I ALTER COLUMN %I TYPE TIMESTAMP WITH TIME ZONE USING %I AT TIME ZONE ''UTC''',
                '{table}', '{column}', '{column}'
            );
        END
        $$;
        """
    )


def _convert_to_timestamp_naive(table: str, column: str) -> None:
    """Idempotent inverse: convert ``timestamptz`` back to naive.

    Uses ``AT TIME ZONE 'UTC'`` to flatten the tz, matching the
    pre-fix state.
    """
    op.execute(
        f"""
        DO $$
        DECLARE
            current_type text;
        BEGIN
            SELECT data_type INTO current_type
            FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = '{table}'
              AND column_name = '{column}';

            IF current_type IS NULL THEN
                RETURN;
            END IF;

            IF current_type = 'timestamp without time zone' THEN
                RETURN;
            END IF;

            EXECUTE format(
                'ALTER TABLE %I ALTER COLUMN %I TYPE TIMESTAMP WITHOUT TIME ZONE USING %I AT TIME ZONE ''UTC''',
                '{table}', '{column}', '{column}'
            );
        END
        $$;
        """
    )


def upgrade() -> None:
    if not _is_postgres():
        # SQLite ROWID handles auto-increment; SQLite has no separate
        # timestamptz type. Nothing to do.
        return

    for table in IDENTITY_TABLES:
        _add_identity(table)

    for table, columns in TIMEZONE_COLUMNS.items():
        for column in columns:
            _convert_to_timestamptz(table, column)


def downgrade() -> None:
    if not _is_postgres():
        return

    for table, columns in TIMEZONE_COLUMNS.items():
        for column in columns:
            _convert_to_timestamp_naive(table, column)

    for table in IDENTITY_TABLES:
        _drop_identity(table)
