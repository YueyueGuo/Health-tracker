"""Persist live Railway fixes: id IDENTITY + timezone-aware datetimes.

Revision ID: a9d2f6c1e3b7
Revises: f9c2e1a45b80
Create Date: 2026-05-24

Background
----------
Two SQLite → Postgres migration regressions were patched live against
the Railway database during the audit-001 mission and never landed in
the migration history:

1. **No autoincrement on ``id`` columns.** SQLite implicitly
   auto-increments ``INTEGER PRIMARY KEY``; Postgres does not. The
   ``create_all``-generated schema on Railway had 14 tables with
   ``id bigint NOT NULL`` and no DEFAULT or IDENTITY, so every INSERT
   that didn't supply ``id`` manually failed with
   ``NotNullViolationError``. Live fix: ``scripts/fix_id_autoincrement.py``
   added ``GENERATED BY DEFAULT AS IDENTITY`` to each affected table.

2. **DateTime columns declared without ``timezone=True``.** The Railway
   columns are ``TIMESTAMP WITH TIME ZONE`` but the SQLAlchemy models
   declared them as bare ``DateTime``, causing asyncpg to refuse to
   bind tz-aware Python datetimes. Live fix on ``main`` (commits
   ``e87220f``, ``35d648f``) added ``timezone=True`` to every affected
   column declaration.

Both fixes work against the current Railway DB but exist nowhere in
the migration history. A fresh deploy or a Postgres restore would
regress. This migration locks both in.

The migration is **Postgres-only DDL** — IDENTITY syntax and ``ALTER
COLUMN ... TYPE timestamptz USING ... AT TIME ZONE 'UTC'`` are both
Postgres features. On SQLite the upgrade/downgrade are no-ops (the
column types are already correct on a fresh SQLite ``create_all`` and
SQLite's ROWID auto-increment is already in place). Both branches are
idempotent: re-running the upgrade is safe.
"""
